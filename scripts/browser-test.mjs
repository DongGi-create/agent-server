import { readFileSync,mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
import { dataDir,config } from '../src/config.mjs';
const runtime=join(process.env.USERPROFILE,'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs');
const {chromium}=await import(pathToFileURL(runtime).href);
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
const token=readFileSync(join(dataDir,'access-token'),'utf8').trim();
await page.goto('http://127.0.0.1:'+config.port+'/#'+token);
await page.locator('#workspace').waitFor({state:'visible'});
await page.getByRole('button',{name:/시스템 연결/}).first().click();
await page.locator('#chat-title').waitFor({state:'visible'});
assert.match(await page.locator('#messages').innerText(),/녹색/);
mkdirSync(join(dataDir,'screenshots'),{recursive:true});
await page.screenshot({path:join(dataDir,'screenshots','desktop.png'),fullPage:true});
await page.getByRole('button',{name:'결정 대기',exact:false}).first().click();
await page.locator('#view-decisions').waitFor({state:'visible'});
assert.match(await page.locator('#decisions').innerText(),/지금은/);
await page.getByRole('button',{name:'연결·설정'}).click();await page.getByRole('button',{name:'5분 접속 코드 발급'}).click();
await page.waitForFunction(()=>/^\d{8}$/.test(document.querySelector('#pair-code').textContent));
const code=await page.locator('#pair-code').innerText();
const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});const phone=await mobile.newPage();
phone.on('pageerror',e=>errors.push(e.message));await phone.goto('http://127.0.0.1:'+config.port+'/');await phone.locator('#login').waitFor({state:'visible'});
await phone.getByLabel('PC에서 발급한 접속 코드').fill(code);await phone.getByRole('button',{name:'작업실 연결'}).click();await phone.locator('#workspace').waitFor({state:'visible'});
assert.ok(await phone.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
await phone.screenshot({path:join(dataDir,'screenshots','mobile.png'),fullPage:true});
const replay=await fetch('http://127.0.0.1:'+config.port+'/api/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({code})});assert.equal(replay.status,401);
const csrf=await page.evaluate(async()=>{const r=await fetch('/api/digest',{method:'POST',headers:{'Content-Type':'application/json'},body:'{}'});return r.status;});assert.equal(csrf,200);
assert.deepEqual(errors,[]);await browser.close();console.log('PASS: desktop/mobile layout, real task chat, decision view, pairing login, one-time code, zero browser errors.');
